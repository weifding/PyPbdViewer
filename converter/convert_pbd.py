"""
Convert PyPbdViewer JSON output to TypeScript.

PBD has no recoverable PowerScript source, so we emit:
- Window / UserObject classes with empty event handlers (stub).
- Global function exports with TODO stubs.
- DataWindow as a typed interface.
- SQL strings recovered from the binary attached as leading comments.
"""
from __future__ import annotations
import json, sys, re
from pathlib import Path


PB_RUNTIME_IMPORT = "import { NonVisualObject, Window, Application, PB } from './pb-runtime';"


def emit_for_idx(idx: dict, out_dir: Path):
    out_dir.mkdir(parents=True, exist_ok=True)
    by_kind = {}
    for e in idx["entries"]:
        by_kind.setdefault(e["kind"], []).append(e)

    # SQL list to attach per file is tricky; just dump a global sql.ts.
    import json as _json
    sql_lines = ["// SQL statements recovered from PBD binary.", "// Auto-generated by pbtots.", "export const recoveredSql: string[] = ["]
    for s in idx["sql"][:200]:
        # Clean: strip DAT* binary markers and control chars.
        raw = s["text"]
        cleaned = raw.replace("DAT*", " ")
        cleaned = "".join(ch if ch.isprintable() or ch in "\t" else " " for ch in cleaned)
        cleaned = " ".join(cleaned.split())  # collapse whitespace
        lit = _json.dumps(cleaned, ensure_ascii=False)
        sql_lines.append(f"  {lit},")
    sql_lines.append("];")
    (out_dir / "recovered-sql.ts").write_text("\n".join(sql_lines), encoding="utf-8")

    emitted = set()

    for kind, items in by_kind.items():
        for e in items:
            name = e["name"]
            if name in emitted:
                continue
            emitted.add(name)

            if kind == "window":
                body = [
                    f"// PBD object: {name}  (kind=window)",
                    PB_RUNTIME_IMPORT,
                    "",
                    f"export class {name} extends Window {{",
                    "  // Recovered event scripts are not available from compiled PBD.",
                    "  // Override these handlers in your app to port behavior.",
                    "  public open(): void {}",
                    "  public close(): void {}",
                    "  public resize(): void {}",
                    "}",
                ]
            elif kind == "userobject":
                body = [
                    f"// PBD object: {name}  (kind=userobject)",
                    PB_RUNTIME_IMPORT,
                    "",
                    f"export class {name} extends NonVisualObject {{",
                    "  public constructor() { super(); }",
                    "}",
                ]
            elif kind == "globalfunction":
                body = [
                    f"// PBD global function: {name}",
                    PB_RUNTIME_IMPORT,
                    "",
                    f"export function {name}(..._args: any[]): any {{",
                    "  // TODO: body stripped during PBD compile.",
                    "  return null as any;",
                    "}",
                ]
            elif kind == "datawindow":
                body = [
                    f"// PBD DataWindow: {name}",
                    "// Typed placeholder — columns must be filled from the .dwo descriptor.",
                    f"export interface {name} {{",
                    "  [column: string]: any;",
                    "}",
                ]
            else:
                continue

            (out_dir / f"{name}.ts").write_text("\n".join(body), encoding="utf-8")


def main():
    if len(sys.argv) < 3:
        print("usage: convert_pbd.py <pbd.json> <out_dir>")
        sys.exit(1)
    idx = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    emit_for_idx(idx, Path(sys.argv[2]))
    print(f"converted {len(idx['entries'])} entries -> {sys.argv[2]}")


if __name__ == "__main__":
    main()
